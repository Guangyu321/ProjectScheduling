const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const out=path.resolve(__dirname,'../../.runtime/browser-verification');fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('response',async response=>{if(response.status()>=400)console.log('HTTP_ERROR',response.status(),response.url(),await response.text());});
 try{
  await page.goto(process.env.CONSOLE_URL||'http://127.0.0.1:5173');
  await page.waitForFunction(()=>document.getElementById('connection').textContent==='已连接');
  assert.equal(await page.evaluate(()=>new URL(window.LAB_CONFIG.apiBase).origin!==location.origin),true,'Frontend and API must have distinct origins');
  const previousHistory=await page.evaluate(async()=>{const r=await fetch(window.LAB_CONFIG.apiBase+'/api/v1/history');return (await r.json()).length;});
  await page.screenshot({path:path.join(out,'01-empty.png'),fullPage:true});
  assert.ok(['未开始','已完成','已取消'].includes(await page.locator('#stat-state').innerText()));
  await page.locator('#new-run').click();
  await page.locator('#new-form button[type=submit]').click();
  await page.waitForFunction(()=>document.getElementById('stat-state').textContent==='运行中');
  await page.locator('#pause').click();
  await page.waitForFunction(()=>document.getElementById('stat-state').textContent==='已暂停');
  await page.screenshot({path:path.join(out,'02-paused.png'),fullPage:true});
  await page.locator('#resume').click();
  await page.waitForFunction(()=>document.getElementById('stat-state').textContent==='运行中');
  await page.locator('#cancel').click();
  await page.locator('#cancel-reason').fill('浏览器验收：取消当前模拟批次');
  await page.locator('#cancel-form button[type=submit]').click();
  await page.waitForFunction(()=>document.getElementById('stat-state').textContent==='已取消');
  await page.locator('#new-run').click();
  await page.locator('#scenario').selectOption('unknown');
  await page.locator('#new-form button[type=submit]').click();
  await page.waitForFunction(()=>document.getElementById('stat-state').textContent==='等待核实');
  await page.locator('[data-view=recovery]').click();
  await page.locator('[data-ack]').click();
  await page.waitForFunction(()=>document.querySelector('[data-ack]')?.disabled);
  await page.locator('[data-resolve]').click();
  await page.locator('#observed-plate').fill('plate_01');
  await page.locator('#observed-location').fill('scanner_1.slot1');
  await page.locator('#resolve-reason').fill('模拟验收：确认板已放置到扫码器');
  await page.locator('#observation').fill('核对 plate_01 身份和扫码器 slot1，机械臂停止，目标位置一致。');
  await page.locator('#device-stopped').check();
  await page.screenshot({path:path.join(out,'03-recovery.png'),fullPage:true});
  await page.locator('#resolve-form button[type=submit]').click();
  await page.waitForFunction(()=>document.getElementById('stat-state').textContent==='已暂停');
  await page.locator('[data-view=overview]').click();
  await page.locator('#resume').click();
  await page.waitForFunction(()=>document.getElementById('stat-state').textContent==='已完成',{},{timeout:60000});
  assert.match(await page.locator('#stat-progress').innerText(),/24\s*\/\s*24/);
  await page.screenshot({path:path.join(out,'04-completed.png'),fullPage:true});
  await page.locator('[data-view=devices]').click();
  assert.equal(await page.locator('.device').count(),10);
  await page.screenshot({path:path.join(out,'05-devices.png'),fullPage:true});
  await page.locator('[data-view=history]').click();
  await page.waitForFunction(count=>document.querySelectorAll('#history-rows tr').length===count,previousHistory+2);
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-view=overview]').click();
  await page.screenshot({path:path.join(out,'06-mobile.png'),fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false,'Mobile page must not overflow horizontally');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({status:'passed',actions:['create','pause','resume','cancel','acknowledge','manual_recovery','complete','history'],screenshots:6,pageErrors:errors}));
 }catch(e){console.log('PAGE',await page.locator('body').innerText());await page.screenshot({path:path.join(out,'failure.png'),fullPage:true});throw e;}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
